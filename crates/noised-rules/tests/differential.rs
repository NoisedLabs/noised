#[test]
fn differential_vectors_are_current() {
    let r = run(RULES_CASES, GRAPH_CASES);
    let text = render(&r);
    let path = vectors_path();
    if [REGEN, LEGACY_REGEN]
        .iter()
        .any(|k| std::env::var(k).is_ok_and(|v| v == "1"))
    {
        std::fs::write(&path, &text).unwrap();
        return;
    }
    let stored = std::fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("{}: {e}; generate it with {REGEN}=1", path.display()));
    assert!(
        stored.replace("\r\n", "\n") == text,
        "{} is stale: regenerate with {REGEN}=1 cargo test -p noised-rules --test differential, then review the diff",
        path.display()
    );
}


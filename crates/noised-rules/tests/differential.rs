/// FNV-1a 64.
fn fnv(bytes: &[u8]) -> u64 {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for b in bytes {
        h ^= u64::from(*b);
        h = h.wrapping_mul(0x0100_0000_01b3);
    }
    h
}

/// The generator's own little-endian writer (independent of the encoders
/// under test).
#[derive(Default)]
struct W(Vec<u8>);

impl W {
    fn u8(&mut self, v: u8) {
        self.0.push(v);
    }
    fn u16(&mut self, v: u16) {
        self.0.extend_from_slice(&v.to_le_bytes());
    }
    fn u32(&mut self, v: u32) {
        self.0.extend_from_slice(&v.to_le_bytes());
    }
    fn u64(&mut self, v: u64) {
        self.0.extend_from_slice(&v.to_le_bytes());
    }
    fn bytes(&mut self, b: &[u8]) {
        self.0.extend_from_slice(b);
    }
    fn node(&mut self, n: &Node) {
        self.u8(n.op);
        self.u8(n.a);
        self.u64(n.arg);
    }
}

/// `b[at] = v` if in range.
fn set(b: &mut [u8], at: usize, v: u8) {
    if let Some(x) = b.get_mut(at) {
        *x = v;
    }
}

/// `b[at..at + v.len()] = v` if entirely in range.
fn put(b: &mut [u8], at: usize, v: &[u8]) {
    if let Some(x) = b.get_mut(at..at + v.len()) {
        x.copy_from_slice(v);
    }
}

/// A field byte: an interesting value or a small one.
fn small_u8(rng: &mut Rng) -> u8 {
    if rng.coin() {
        rng.pick(&U8S)
    } else {
        rng.below(6) as u8
    }
}

/// A wide field value: an interesting one or a small one.
fn wide_field(rng: &mut Rng) -> u64 {
    if rng.coin() {
        rng.pick(&WIDES)
    } else {
        rng.below(4)
    }
}

/// One more condition node (TRUE) at the end, counted in the header
/// (`UnreferencedNode` for an otherwise valid program).
fn append_node(b: &mut Vec<u8>) {
    if let Some(n) = b.get_mut(7) {
        *n = n.wrapping_add(1);
    }
    b.extend_from_slice(&[0; 10]);
}

/// `rng.wide()` of `tests/common` (biased toward edges).
fn wide(rng: &mut Rng) -> u64 {
    rng.wide()
}

/// Random byte edits shared by both formats: 0 a random byte, 1 an
/// interesting byte, 2 a bit flip, otherwise truncate or append.
fn byte_edit(rng: &mut Rng, b: &mut Vec<u8>, kind: u64) {
    match kind {
        0..=2 => {
            if b.is_empty() {
                return;
            }
            let p = rng.below(b.len() as u64) as usize;
            match kind {
                0 => {
                    let v = rng.next() as u8;
                    b[p] = v;
                }
                1 => {
                    let v = rng.pick(&U8S);
                    b[p] = v;
                }
                _ => {
                    let bit = rng.below(8);
                    b[p] ^= 1 << bit;
                }
            }
        }
        _ => {
            if rng.coin() && !b.is_empty() {
                // Mostly a few bytes off the end, sometimes down to a stub.
                let keep = if rng.one_in(4) {
                    rng.below(b.len().min(48) as u64) as usize
                } else {
                    b.len() - 1 - rng.below(b.len().min(16) as u64) as usize
                };
                b.truncate(keep);
            } else {
                let k = 1 + rng.below(3);
                for _ in 0..k {
                    let v = rng.next() as u8;
                    b.push(v);
                }
            }
        }
    }
}

/// A random well-formed postfix condition of 1..=`max_len` nodes.
fn gen_cond(rng: &mut Rng, max_len: usize, leaf: &mut dyn FnMut(&mut Rng) -> Node) -> Vec<Node> {
    let max_leaves = max_len.div_ceil(2).min(24);
    let leaves = 1 + rng.below(max_leaves as u64) as usize;
    let mut out = Vec::new();
    let (mut depth, mut left) = (0usize, leaves);
    while left > 0 || depth > 1 {
        let can_push = left > 0 && depth < 16;
        let can_combine = depth >= 2;
        if can_push && (!can_combine || rng.below(3) != 0) {
            let n = if rng.one_in(8) {
                Node::new(if rng.coin() { op::TRUE } else { op::FALSE }, 0, 0)
            } else {
                leaf(rng)
            };
            out.push(n);
            left -= 1;
            depth += 1;
        } else {
            let o = if rng.coin() { op::AND } else { op::OR };
            out.push(Node::new(o, 0, 0));
            depth -= 1;
        }
        let needed = left + (depth + left).saturating_sub(1);
        if out.len() + 1 + needed <= max_len && rng.one_in(5) {
            out.push(Node::new(op::NOT, 0, 0));
        }
    }
    assert!(!out.is_empty() && out.len() <= max_len);
    out
}


struct RulesCase {
    guard: u32,
    bytes: Vec<u8>,
    ctxs: Vec<TransferCtx>,
    /// (value, arg, supply)
    thresholds: Vec<(u64, u64, u64)>,
}

fn bps_arg(rng: &mut Rng) -> u64 {
    BPS_FLAG | rng.pick(&[1u64, 2, 10, 50, 100, 250, 1_000, 5_000, 9_999, 10_000])
}

fn rules_leaf(rng: &mut Rng, n_keys: usize, g: u32) -> Node {
    loop {
        let kind = rng.below(10);
        let n = match kind {
            0 => Node::new(op::rules::IS_BUY, 0, 0),
            1 => Node::new(op::rules::IS_P2P, 0, 0),
            2 | 3 => {
                let o = if kind == 2 {
                    op::rules::TIME_LT
                } else {
                    op::rules::TIME_GE
                };
                Node::new(o, 0, rng.range(0, u64::from(g)))
            }
            4 | 5 => {
                let o = if kind == 4 {
                    op::rules::AMOUNT_GT
                } else {
                    op::rules::DEST_BAL_AFTER_GT
                };
                let arg = if rng.coin() {
                    bps_arg(rng)
                } else {
                    wide(rng) & !BPS_FLAG
                };
                Node::new(o, 0, arg)
            }
            6..=8 => {
                if n_keys == 0 {
                    continue;
                }
                let all = ((1u16 << n_keys) - 1) as u8;
                let mask = (rng.next() as u8 & all).max(1);
                let o = op::rules::DEST_OWNER_IN + rng.below(3) as u8;
                Node::new(o, mask, 0)
            }
            _ => Node::new(op::rules::TX_IX_COUNT_GT, 0, rng.below(20)),
        };
        return n;
    }
}

fn is_mask_op(o: u8) -> bool {
    (op::rules::DEST_OWNER_IN..=op::rules::TOP_PROGRAM_IN).contains(&o)
}

/// The generator's own threshold (128-bit, saturating), for picking amounts
/// near caps.
fn gen_cap(arg: u64, supply: u64) -> u64 {
    if arg & BPS_FLAG == 0 {
        return arg;
    }
    let t = u128::from(supply) * u128::from(arg & 0xFFFF) / 10_000;
    u64::try_from(t).unwrap_or(u64::MAX)
}

fn near_cap(rng: &mut Rng, caps: &[u64]) -> u64 {
    if !caps.is_empty() && rng.coin() {
        let t = rng.pick(caps);
        let d = rng.pick(&[0u64, 1, 2]);
        t.saturating_add(d).saturating_sub(1)
    } else {
        wide(rng)
    }
}

fn who(rng: &mut Rng, keys: &[[u8; 32]]) -> [u8; 32] {
    if !keys.is_empty() && rng.below(3) != 0 {
        rng.pick(keys)
    } else {
        rng.key()
    }
}

/// (from, to, effect, code, arg, cond_off, cond_len) of the model's rules.
type MRule = (u32, u32, u8, u8, u64, u8, u8);

fn gen_tctx(
    rng: &mut Rng,
    guard: u32,
    keys: &[[u8; 32]],
    rs: &[MRule],
    nodes: &[Node],
) -> TransferCtx {
    let g = i64::from(guard.min(MAX_GUARD_SECS));
    let windows: Vec<i64> = rs
        .iter()
        .flat_map(|r| [i64::from(r.0), i64::from(r.1)])
        .collect();
    let times: Vec<i64> = nodes
        .iter()
        .filter(|n| n.op == op::rules::TIME_LT || n.op == op::rules::TIME_GE)
        .map(|n| n.arg as i64)
        .collect();
    let branch = rng.below(5);
    let now_rel = if branch == 0 && !windows.is_empty() {
        let w = rng.pick(&windows);
        let d = rng.pick(&[-1i64, 0, 1]);
        w + d
    } else if branch == 1 && !times.is_empty() {
        let t = rng.pick(&times);
        let d = rng.pick(&[-1i64, 0, 1]);
        t + d
    } else if branch == 2 {
        rng.pick(&[-1i64, 0, g - 1, g, i64::MIN, i64::MAX])
    } else {
        rng.below(g as u64 + 10) as i64 - 5
    };
    let is_buy = rng.coin();
    let is_p2p = rng.coin();
    let supply = match rng.below(4) {
        0 => rng.pick(&[0u64, 1, 9_999, 10_000, 10_001, u64::MAX]),
        1 => 1_000_000_000_000_000_000,
        _ => wide(rng),
    };
    let caps: Vec<u64> = rs
        .iter()
        .filter(|r| r.2 != effect::DENY)
        .map(|r| r.4)
        .chain(
            nodes
                .iter()
                .filter(|n| n.op == op::rules::AMOUNT_GT || n.op == op::rules::DEST_BAL_AFTER_GT)
                .map(|n| n.arg),
        )
        .map(|a| gen_cap(a, supply))
        .collect();
    let amount = near_cap(rng, &caps);
    let dest_balance_after = near_cap(rng, &caps);
    let dest_owner = who(rng, keys);
    let src_owner = who(rng, keys);
    let top_program = who(rng, keys);
    let tx_ix_count = rng.pick(&[0u16, 1, 2, 3, 4, 5, 10, 19, 20, 64, u16::MAX]);
    TransferCtx {
        now_rel,
        is_buy,
        is_p2p,
        amount,
        dest_balance_after,
        supply,
        dest_owner,
        src_owner,
        top_program,
        tx_ix_count,
    }
}

fn mutate_rules(rng: &mut Rng, b: &mut Vec<u8>, n_keys: usize, n_rules: usize, n_nodes: usize) {
    let key_at = |k: usize| 12 + 32 * k;
    let rule_at = |r: usize| 12 + 32 * n_keys + 20 * r;
    let node_at = |n: usize| 12 + 32 * n_keys + 20 * n_rules + 10 * n;
    let kind = rng.below(14);
    match kind {
        0..=2 => byte_edit(rng, b, kind),
        3 => {
            let at = rng.pick(&[0usize, 4, 5, 6, 7, 8, 9, 10, 11]);
            let v = small_u8(rng);
            set(b, at, v);
        }
        4 => {
            let r = rng.below(n_rules as u64) as usize;
            let off = rng.pick(&[8usize, 9, 10, 11]);
            let v = small_u8(rng);
            set(b, rule_at(r) + off, v);
        }
        5 => {
            let r = rng.below(n_rules as u64) as usize;
            let off = rng.pick(&[0usize, 4]);
            let v = rng.pick(&U32S);
            put(b, rule_at(r) + off, &v.to_le_bytes());
        }
        6 => {
            let r = rng.below(n_rules as u64) as usize;
            let v = wide_field(rng);
            put(b, rule_at(r) + 12, &v.to_le_bytes());
        }
        7..=9 => {
            if n_nodes == 0 {
                return;
            }
            let n = rng.below(n_nodes as u64) as usize;
            match kind {
                7 => {
                    let v = rng.pick(&OPS);
                    set(b, node_at(n), v);
                }
                8 => {
                    let v = rng.pick(&U8S);
                    set(b, node_at(n) + 1, v);
                }
                _ => {
                    let v = wide_field(rng);
                    put(b, node_at(n) + 2, &v.to_le_bytes());
                }
            }
        }
        10 => {
            if n_nodes == 0 {
                return;
            }
            let n = rng.below(n_nodes as u64) as usize;
            let k = 1 + rng.below(24) as usize;
            for i in n..(n + k).min(n_nodes) {
                put(b, node_at(i), &[0; 10]); // TRUE
            }
        }
        11 => {
            if n_keys == 0 {
                return;
            }
            let k = rng.below(n_keys as u64) as usize;
            if n_keys >= 2 && rng.coin() {
                let j = rng.below(n_keys as u64) as usize;
                if let Some(src) = b.get(key_at(j)..key_at(j) + 32) {
                    let src = src.to_vec();
                    put(b, key_at(k), &src);
                }
            } else {
                put(b, key_at(k), &[0u8; 32]);
            }
        }
        12 => append_node(b),
        _ => byte_edit(rng, b, 3),
    }
}

fn gen_rules_case(rng: &mut Rng) -> RulesCase {
    let guard = match rng.below(8) {
        0 => rng.pick(&GUARDS),
        1 => MAX_GUARD_SECS,
        _ => rng.range(2, u64::from(MAX_GUARD_SECS)) as u32,
    };
    let g = guard.min(MAX_GUARD_SECS);
    let mut n_keys = rng.below(9) as usize;
    let mut keys: Vec<[u8; 32]> = Vec::new();
    for _ in 0..n_keys {
        keys.push(rng.key());
    }
    let n_rules = 1 + rng.below(16) as usize;
    let mut budget = if rng.one_in(4) {
        64
    } else {
        rng.range(n_rules as u64, 64) as usize
    };
    let mut rs: Vec<MRule> = Vec::new();
    let mut nodes: Vec<Node> = Vec::new();
    for i in 0..n_rules {
        let rules_after = n_rules - i - 1;
        let max_len = (budget - rules_after).clamp(1, 24);
        let cond = gen_cond(rng, max_len, &mut |r| rules_leaf(r, n_keys, g));
        budget -= cond.len();
        let from = rng.below(u64::from(g.max(1))) as u32;
        let to = rng.range(u64::from(from) + 1, u64::from(g).max(u64::from(from) + 1)) as u32;
        let code = rng.below(64) as u8;
        let eff = 1 + rng.below(3) as u8;
        let arg = if eff == effect::DENY {
            0
        } else if rng.coin() {
            bps_arg(rng)
        } else {
            wide(rng).clamp(1, (1 << 63) - 1)
        };
        rs.push((
            from,
            to,
            eff,
            code,
            arg,
            nodes.len() as u8,
            cond.len() as u8,
        ));
        nodes.extend_from_slice(&cond);
    }
    // Every key must be used: widen the first key mask, or drop the keys.
    let all = ((1u16 << n_keys) - 1) as u8;
    let used = nodes
        .iter()
        .filter(|n| is_mask_op(n.op))
        .fold(0u8, |m, n| m | n.a);
    if used != all {
        match nodes.iter_mut().find(|n| is_mask_op(n.op)) {
            Some(n) => n.a |= all & !used,
            None => {
                n_keys = 0;
                keys.clear();
            }
        }
    }
    let mut w = W::default();
    w.bytes(b"PXR1");
    for v in [
        1,
        n_keys as u8,
        n_rules as u8,
        nodes.len() as u8,
        0,
        0,
        0,
        0,
    ] {
        w.u8(v);
    }
    for k in &keys {
        w.bytes(k);
    }
    for r in &rs {
        w.u32(r.0);
        w.u32(r.1);
        w.u8(r.5);
        w.u8(r.6);
        w.u8(r.2);
        w.u8(r.3);
        w.u64(r.4);
    }
    for n in &nodes {
        w.node(n);
    }
    let mut bytes = w.0;
    let n_mut = rng.pick(&[0usize, 0, 0, 0, 1, 1, 1, 2, 2, 3]);
    for _ in 0..n_mut {
        mutate_rules(rng, &mut bytes, n_keys, n_rules, nodes.len());
    }
    let mut ctxs = Vec::new();
    for _ in 0..SAMPLES {
        ctxs.push(gen_tctx(rng, guard, &keys, &rs, &nodes));
    }
    let mut thresholds = Vec::new();
    for _ in 0..2 {
        let arg = match rng.below(3) {
            0 => rng.pick(&WIDES),
            1 => BPS_FLAG | rng.below(0x1_0000),
            _ => rng.next() | BPS_FLAG,
        };
        let supply = wide(rng);
        let value = wide(rng);
        thresholds.push((value, arg, supply));
    }
    RulesCase {
        guard,
        bytes,
        ctxs,
        thresholds,
    }
}

fn bit(b: bool) -> char {
    if b {
        '1'
    } else {
        '0'
    }
}

/// The full result line of a rules case.
fn rules_line(c: &RulesCase) -> String {
    let mut r = String::new();
    match RuleSet::verify(&c.bytes, c.guard) {
        Ok(_) => write!(r, "ok:{}", hex(&rules_hash::<Sha2>(&c.bytes))).unwrap(),
        Err(e) => r.push_str(e.name()),
    }
    let parsed = RuleSet::parse(&c.bytes);
    r.push(' ');
    r.push_str(parsed.err().map_or("ok", |e| e.name()));
    if let Ok(set) = parsed {
        let back = RulesProgram::decode(&c.bytes).unwrap().encode().unwrap();
        r.push_str(if back == c.bytes { " rt" } else { " RT!" });
        for ctx in &c.ctxs {
            r.push(' ');
            match set.evaluate(ctx) {
                Ok(()) => r.push('-'),
                Err(v) => write!(r, "{}.{}", v.rule, v.code).unwrap(),
            }
            r.push('/');
            for i in 0..=set.rule_count() {
                r.push(match set.condition(i, ctx) {
                    Some(true) => '1',
                    Some(false) => '0',
                    None => 'x',
                });
            }
        }
    }
    for &(value, arg, supply) in &c.thresholds {
        let t = threshold(arg, supply);
        write!(
            r,
            " t{t}:{}{}{}",
            bit(exceeds(value, arg, supply)),
            bit(exceeds(t, arg, supply)),
            bit(exceeds(t.saturating_add(1), arg, supply))
        )
        .unwrap();
    }
    r
}


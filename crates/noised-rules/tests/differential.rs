fn verdicts(line: &str) -> (&str, &str) {
    let mut it = line.split(' ');
    let v = it.next().unwrap();
    let p = it.next().unwrap();
    (if v.starts_with("ok:") { "ok" } else { v }, p)
}

fn entry(bytes: &[u8], line: &str) -> String {
    let (v, p) = verdicts(line);
    format!(
        "{}:{:016x} {v} {p} {:016x}",
        bytes.len(),
        fnv(bytes),
        fnv(line.as_bytes())
    )
}

fn rules_case(i: usize) -> (RulesCase, String) {
    let c = gen_rules_case(&mut Rng::new(RULES_SEED.wrapping_add(i as u64)));
    let line = rules_line(&c);
    (c, line)
}

fn graph_case(i: usize) -> (GraphCase, String) {
    let c = gen_graph_case(&mut Rng::new(GRAPH_SEED.wrapping_add(i as u64)));
    let line = graph_line(&c);
    (c, line)
}

struct Run {
    rules: Vec<String>,
    graph: Vec<String>,
    rules_verify: BTreeMap<String, usize>,
    graph_verify: BTreeMap<String, usize>,
    graph_due: BTreeMap<char, usize>,
}

fn run(rules_cases: usize, graph_cases: usize) -> Run {
    let mut out = Run {
        rules: Vec::new(),
        graph: Vec::new(),
        rules_verify: BTreeMap::new(),
        graph_verify: BTreeMap::new(),
        graph_due: BTreeMap::new(),
    };
    for i in 0..rules_cases {
        let (c, line) = rules_case(i);
        *out.rules_verify
            .entry(verdicts(&line).0.to_string())
            .or_default() += 1;
        out.rules.push(entry(&c.bytes, &line));
    }
    for i in 0..graph_cases {
        let (c, line) = graph_case(i);
        *out.graph_verify
            .entry(verdicts(&line).0.to_string())
            .or_default() += 1;
        if verdicts(&line).0 == "ok" {
            for sample in line.split(' ').skip(3).filter(|s| !s.starts_with('s')) {
                for ch in sample.split('/').take(2).flat_map(|s| s.chars()) {
                    *out.graph_due.entry(ch).or_default() += 1;
                }
            }
        }
        out.graph.push(entry(&c.bytes, &line));
    }
    out
}

fn json_list(out: &mut String, items: &[String]) {
    out.push_str("[\n");
    for (i, s) in items.iter().enumerate() {
        out.push_str("      ");
        out.push_str(&serde_json::to_string(s).unwrap());
        out.push_str(if i + 1 < items.len() { ",\n" } else { "\n" });
    }
    out.push_str("    ]");
}

fn render(r: &Run) -> String {
    let summary = |m: &BTreeMap<String, usize>| serde_json::to_string(m).unwrap();
    let mut s = String::new();
    s.push_str("{\n");
    writeln!(s, "  \"format\": \"{FORMAT}\",").unwrap();
    // Provenance text pinned byte-for-byte in the committed vector file (written before the rename to Noised): kept so the file stays identical.
    s.push_str("  \"generator\": \"crates/phalanx-rules/tests/differential.rs, mirrored by the SDK's test/programmable/differential.ts\",\n");
    writeln!(
        s,
        "  \"regenerate\": \"PHALANX_REGEN_VECTORS=1 cargo test -p phalanx-rules --test differential\","
    )
    .unwrap();
    s.push_str("  \"notes\": \"Case i of a format uses SplitMix64 seeded with seed + i. Entry: <len>:<FNV-1a 64 of the bytes> <verify> <parse> <FNV-1a 64 of the full result line>; PHALANX_DIFF_DUMP=rules:<i> (or graph:<i>) prints a full line. names: Error and NotDue in discriminant order (the name contract).\",\n");
    let names = |all: Vec<&str>| serde_json::to_string(&all).unwrap();
    s.push_str("  \"names\": {\n");
    writeln!(
        s,
        "    \"errors\": {},",
        names(Error::ALL.iter().map(|e| e.name()).collect())
    )
    .unwrap();
    writeln!(
        s,
        "    \"not_due\": {}",
        names(NotDue::ALL.iter().map(|e| e.name()).collect())
    )
    .unwrap();
    s.push_str("  },\n");
    s.push_str("  \"rules\": {\n");
    writeln!(s, "    \"seed\": \"{RULES_SEED}\",").unwrap();
    writeln!(s, "    \"samples\": {SAMPLES},").unwrap();
    writeln!(s, "    \"verify\": {},", summary(&r.rules_verify)).unwrap();
    s.push_str("    \"cases\": ");
    json_list(&mut s, &r.rules);
    s.push_str("\n  },\n  \"graph\": {\n");
    writeln!(s, "    \"seed\": \"{GRAPH_SEED}\",").unwrap();
    writeln!(s, "    \"samples\": {SAMPLES},").unwrap();
    writeln!(s, "    \"verify\": {},", summary(&r.graph_verify)).unwrap();
    s.push_str("    \"cases\": ");
    json_list(&mut s, &r.graph);
    s.push_str("\n  }\n}\n");
    s
}


//! Differential parity with the TypeScript SDK (`sdk/src/programmable`).
//!
//! The generator below (format `DIFF1`) is mirrored line for line by the
//! SDK's `test/programmable/differential.ts`: from the same seed both sides
//! build the same programs (plausible ones, then byte and field mutations,
//! so most error orderings and the unverified paths are exercised too), run
//! them through every entry point and must get the same results. The
//! generator writes its bytes with its own little-endian writer and never
//! looks at a result, so the two streams cannot drift apart through the code
//! under test.
//!
//! `tests/vectors/differential.json` holds one entry per case:
//! `"<len>:<fnv> <verify> <parse> <digest>"`, where `<fnv>` is the FNV-1a 64
//! of the generated bytes (both generators agree), `<verify>` / `<parse>` are
//! `ok` or the error name, and `<digest>` is the FNV-1a 64 of the full
//! result line (`rules_line` / `graph_line`: hash, evaluations, conditions,
//! schedules, caps, epochs, shares, thresholds, codec round trip).
//!
//! ```text
//! NOISED_REGEN_VECTORS=1 cargo test -p noised-rules --test differential   # regenerate, then review
//! NOISED_DIFF_DUMP=rules:17 cargo test -p noised-rules --test differential -- --nocapture
//!     # print case 17's full result line (graph:N for a graph)
//! NOISED_DIFF_OUT=<file> NOISED_DIFF_CASES=100000 cargo test -p noised-rules --test differential
//!     # a larger run in the same format (the SDK reads it with NOISED_DIFF_FILE=<file>)
//! ```


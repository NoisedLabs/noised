export function SectionGlyph({ id }: { id: SectionId }): ReactNode {
  const rows = GLYPHS[id];
  const cells: ReactNode[] = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < Math.min(10, row.length); x++) if (row[x] === "#") cells.push(<rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} />);
  });
  return (
    <svg className="wp-h2-glyph" viewBox="0 0 10 10" shapeRendering="crispEdges" aria-hidden="true" focusable="false" fill="currentColor">
      {cells}
    </svg>
  );
}

export type GlyphName = keyof typeof GLYPHS;

function pathOf(rows: readonly string[]): string {
  let d = "";
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== "#") {
        x++;
        continue;
      }
      let w = 1;
      while (row[x + w] === "#") w++;
      d += `M${x} ${y}h${w}v1h-${w}z`;
      x += w;
    }
  });
  return d;
}

const PATHS = new Map<GlyphName, string>();

export function Pixel({ name, size = 22, className = "" }: { name: GlyphName; size?: number; className?: string }): ReactNode {
  const d = useMemo(() => {
    let p = PATHS.get(name);
    if (!p) {
      p = pathOf(GLYPHS[name]);
      PATHS.set(name, p);
    }
    return p;
  }, [name]);
  return (
    <svg className={`dx-px ${className}`} width={size} height={size} viewBox="0 0 11 11" shapeRendering="crispEdges" aria-hidden="true" focusable="false">
      <path d={d} fill="currentColor" />
    </svg>
  );
}

/** A row of square segments: `filled` of `count` lit (a pixel progress bar). */
export function Segments({ count, filled, className = "", label }: { count: number; filled: number; className?: string; label?: string }): ReactNode {
  return (
    <span className={`dx-seg ${className}`} role={label ? "img" : undefined} aria-label={label} aria-hidden={label ? undefined : true}>
      {Array.from({ length: count }, (_, i) => (
        <i key={i} data-on={i < filled ? "1" : "0"} />
      ))}
    </span>
  );
}

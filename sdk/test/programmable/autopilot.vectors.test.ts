/**
 * Parity with the autopilot program itself: test/vectors/programmable/
 * autopilot.json was written by the program's own Rust functions
 * (programs/noised-autopilot src/price.rs, reference.rs, logic.rs and the
 * payload hashes of launchpad.rs) on seeded inputs (generator:
 * test/vectors/programmable/autopilot.gen.rs). Every input is replayed here
 * through the SDK's port and every output must match exactly: prices and
 * bounds, observation histories with the reference's moves, keeper floors,
 * amounts, tips, activation / freshness / apply checks, run records and
 * 2,998 complete `plan_run` decisions on 300 random verified graphs. The
 * file was regenerated for SDK 0.9.0 against the programs as merged after
 * audit round 4: freeze payload v2, revocation payload v3 (with
 * `active_auth`), keepers' partial buybacks (`RemainderTooSmall`, the open
 * run's `partial_spent`, `record_run`'s partial branch, `max_tip`), burns
 * valued at `burn_price` (nothing before graduation) and
 * `reference::lowest`.
 */
import { readFileSync } from "node:fs";

import { sha256 } from "@noble/hashes/sha2.js";
import { describe, expect, it } from "vitest";

import {
  AUTOPILOT,
  AUTOPILOT_ERRORS,
  activationPayload,
  autopilotErrorCode,
  burnPrice,
  buybackCap,
  checkActivation,
  checkApply,
  checkFresh,
  emptyObservations,
  followReference,
  freezePayload,
  fromHex,
  keeperFloor,
  lowestObserved,
  observationWindow,
  planMaxTip,
  planPartial,
  planRun,
  planSpent,
  planValue,
  priceQ64,
  recordObservation,
  recordRunRaw,
  revokePayload,
  runAmount,
  takeTipRaw,
  toHex,
  tokenValue,
  verifyGraphBytes,
  withinPremium,
  buybackMinOut,
  type AuthMark,
  type ObsBucket,
  type PriceState,
  type RawNodeState,
} from "../../src/programmable/index.js";

/* eslint-disable @typescript-eslint/no-explicit-any */
type J = any;

const FILE = new URL("../vectors/programmable/autopilot.json", import.meta.url);
const TEXT = readFileSync(FILE, "utf8").replace(/\r\n/g, "\n");
const V: J = JSON.parse(TEXT);
/** SHA-256 of the copy (LF): regenerate with autopilot.gen.rs and update together. */
const PINNED = "0cca916f5ca5c8e205d1d11856d7ad0d66b51389e7d2b30a148eccecfdcd9fd0";

const b = (s: string): bigint => BigInt(s);
const n = (s: string): number => Number(s);
const ob = (s: string | null): bigint | null => (s === null ? null : BigInt(s));
const bucket = (a: string[]): ObsBucket => ({ index: n(a[0]!), firstAt: n(a[1]!), min: b(a[2]!), max: b(a[3]!) });
const state = (a: J[]): PriceState => ({
  reference: b(a[0]),
  updatedAt: n(a[1]),
  allowance: b(a[2]),
  allowanceAt: n(a[3]),
  observations: [bucket(a[4]), bucket(a[5])],
});
const seenOf = (s: J): { min: bigint; max: bigint } | null => (s === null ? null : { min: b(s.min), max: b(s.max) });
const raw = (a: J[]): RawNodeState => ({ lastRun: b(a[0]), lastSeq: b(a[1]), epochStart: b(a[2]), runsInEpoch: a[3], spentInEpoch: b(a[4]) });
const nodeRec = (o: J): RawNodeState => ({ lastRun: b(o.last_run), lastSeq: b(o.last_seq), epochStart: b(o.epoch_start), runsInEpoch: o.runs_in_epoch, spentInEpoch: b(o.spent_in_epoch) });


describe("autopilot vectors (the program's own functions)", () => {
  it("the copy is the pinned file, generated by the program", () => {
    expect(toHex(sha256(new TextEncoder().encode(TEXT)))).toBe(PINNED);
    // The file is pinned byte for byte: its provenance names the program's directory before the rename to Noised.
    expect(V.generator).toMatch(/phalanx-autopilot/);
  });

  it("constants: the SDK's AUTOPILOT bounds are the program's", () => {
    const c = V.constants;
    expect(AUTOPILOT.UPDATE_TIMELOCK_SECS).toBe(c.UPDATE_TIMELOCK_SECS);
    expect(AUTOPILOT.TIP_LAMPORTS).toBe(BigInt(c.TIP_LAMPORTS));
    expect(AUTOPILOT.TIP_EPOCH_SECS).toBe(c.TIP_EPOCH_SECS);
    expect(AUTOPILOT.TIP_EPOCH_CAP).toBe(BigInt(c.TIP_EPOCH_CAP));
    expect(AUTOPILOT.TIP_MAX_SHARE_BPS).toBe(c.TIP_MAX_SHARE_BPS);
    expect(AUTOPILOT.OBS_BUCKET_SECS).toBe(c.OBS_BUCKET_SECS);
    expect(AUTOPILOT.OBS_MIN_SPAN_SECS).toBe(c.OBS_MIN_SPAN_SECS);
    expect(AUTOPILOT.REF_UP_SQRT_BPS_PER_HOUR).toBe(c.REF_UP_SQRT_BPS_PER_HOUR);
    expect(AUTOPILOT.REF_ALLOWANCE_MAX).toBe(BigInt(c.REF_ALLOWANCE_MAX));
    expect(AUTOPILOT.KEEPER_MIN_POOL_BPS).toBe(c.KEEPER_MIN_POOL_BPS);
    expect(AUTOPILOT.ACCOUNT_LEN).toBe(c.AUTOPILOT_LEN);
    expect(c.AUTOPILOT_LEN).toBe(1_244); // audit round 4: active_auth, active_activate_at, partial_spent appended
    expect(AUTOPILOT.BUYBACK_ACCOUNTS).toBe(c.BUYBACK_ACCOUNTS);
  });

  it("price.rs: price_q64, within_premium, min_out, token_value", () => {
    let count = 0;
    for (const v of V.price) {
      count++;
      switch (v.fn) {
        case "price_q64":
          expect(priceQ64(b(v.sqrt)), JSON.stringify(v)).toBe(ob(v.out));
          break;
        case "within_premium":
          expect(withinPremium(b(v.spot), b(v.ref), b(v.premium)), JSON.stringify(v)).toBe(v.out);
          break;
        case "min_out":
          expect(buybackMinOut(b(v.amount_in), b(v.ref), b(v.premium)), JSON.stringify(v)).toBe(ob(v.out));
          break;
        case "token_value":
          expect(tokenValue(b(v.amount), b(v.sqrt)), JSON.stringify(v)).toBe(b(v.out));
          break;
        default:
          throw new Error(v.fn);
      }
    }
    expect(count).toBe(4_000);
  });

  it("reference.rs: observation histories, the window, the bound and every reference move", () => {
    let ops = 0;
    let moves = 0;
    for (const h of V.reference) {
      const p = state(h.initial);
      for (const o of h.ops) {
        const now = n(o.now);
        if (o.obs) recordObservation(p.observations, now, b(o.spot));
        const seen = observationWindow(p.observations, now);
        expect(seen).toEqual(seenOf(o.seen));
        const moved = followReference(p, seen, now);
        expect(moved).toBe(o.moved);
        expect(buybackCap(p.reference, seen)).toBe(ob(o.cap));
        expect(p).toEqual(state(o.st));
        ops++;
        if (moved) moves++;
      }
    }
    expect(ops).toBeGreaterThan(1_500);
    expect(moves).toBeGreaterThan(300);
    expect(emptyObservations()).toEqual([bucket(["0", "0", "0", "0"]), bucket(["0", "0", "0", "0"])]);
  });

  it("logic.rs: keeper_floor, run_amount, take_tip, check_activation, check_fresh, check_apply, record_run, burn_price, lowest, Plan value / partial / max_tip, payloads", () => {
    const seen = new Set<string>();
    for (const v of V.logic) {
      seen.add(v.fn);
      const where = JSON.stringify(v);
      switch (v.fn) {
        case "keeper_floor":
          expect(keeperFloor(b(v.pool_quote)), where).toBe(b(v.out));
          break;
        case "run_amount": {
          const r = runAmount(v.gated, ob(v.amount), b(v.cap), b(v.available), ob(v.floor));
          expect(r.ok ? { out: r.value, err: null } : { out: null, err: r.error }, where).toEqual({ out: ob(v.out), err: v.err });
          break;
        }
        case "take_tip": {
          let counters = { epochStart: b(v.epoch_start), inEpoch: b(v.in_epoch) };
          for (const s of v.steps) {
            const r = takeTipRaw(counters, b(s.now), b(s.treasury_sol), b(s.value), b(s.max_tip));
            expect(r.tip, where).toBe(b(s.tip));
            expect(r.counters).toEqual({ epochStart: b(s.epoch_start), inEpoch: b(s.in_epoch) });
            counters = r.counters;
          }
          break;
        }
        case "check_activation": {
          const z = new Uint8Array(32);
          const err = checkActivation({
            activeGraph: v.active ? new Uint8Array(32).fill(7) : z,
            pendingGraph: v.pending ? new Uint8Array(32).fill(9) : null,
            frozen: v.frozen,
            now: b(v.now),
            activateAt: b(v.activate_at),
            authUnixTime: b(v.auth_unix_time),
          });
          expect(err, where).toBe(v.err);
          break;
        }
        case "check_fresh": {
          const m = (x: J): AuthMark => ({ slot: b(x.slot), key: fromHex(x.key) });
          expect(checkFresh(m(v.mark), [m(v.marks[0]), m(v.marks[1]), m(v.marks[2])], v.kind), where).toBe(v.err);
          break;
        }
        case "check_apply":
          expect(checkApply(v.pending ? new Uint8Array(32).fill(9) : new Uint8Array(32), b(v.activate_at), v.frozen, b(v.now)), where).toBe(v.err);
          break;
        case "record_run": {
          const r = recordRunRaw(nodeRec(v.node), b(v.seq), v.epoch_secs, b(v.now), b(v.spent), { partial: v.partial, partialSpent: b(v.partial_spent) });
          if (v.err === null) {
            expect(r.ok, where).toBe(true);
            if (r.ok) {
              expect(r.value.node).toEqual(nodeRec(v.out));
              expect(r.value.seq).toBe(b(v.seq_out));
              expect(r.value.partialSpent).toBe(b(v.partial_spent_out));
            }
          } else {
            expect(r.ok ? null : r.error, where).toBe(v.err);
          }
          break;
        }
        case "burn_price":
          expect(burnPrice(v.graduated, b(v.reference), ob(v.lowest)), where).toBe(b(v.out));
          break;
        case "lowest":
          expect(lowestObserved([bucket(v.obs[0]), bucket(v.obs[1])], n(v.now)), where).toBe(ob(v.out));
          break;
        case "plan_value": {
          const a = b(v.amount);
          const plan =
            v.kind === "buyback"
              ? { kind: "buyback" as const, amountIn: a, minOut: 1n, partial: v.partial as boolean }
              : v.kind === "burn"
                ? { kind: "burn" as const, amount: a }
                : { kind: "distribute" as const, shares: [a / 2n, a - a / 2n, 0n, 0n, 0n, 0n, 0n, 0n], total: a };
          expect(planValue(plan, b(v.burn_price), b(v.kept)), where).toBe(b(v.value));
          expect(planPartial(plan), where).toBe(v.is_partial);
          expect(planMaxTip(plan, b(v.p1)), where).toBe(b(v.max_tip));
          break;
        }
        case "payloads": {
          const ap = fromHex(v.autopilot);
          const gh = fromHex(v.graph_hash);
          expect(toHex(activationPayload(ap, gh, b(v.activate_at))), where).toBe(v.activate);
          // Freeze payload v2 (review 4, R5) and revocation payload v3 with active_auth (audit 4, A4-3).
          expect(toHex(freezePayload(ap, gh, b(v.not_after))), where).toBe(v.freeze);
          expect(toHex(revokePayload(ap, gh, fromHex(v.operator), fromHex(v.active_auth))), where).toBe(v.revoke);
          break;
        }
        default:
          throw new Error(v.fn);
      }
    }
    expect([...seen].sort()).toEqual([
      "burn_price",
      "check_activation",
      "check_apply",
      "check_fresh",
      "keeper_floor",
      "lowest",
      "payloads",
      "plan_value",
      "record_run",
      "run_amount",
      "take_tip",
    ]);
    // The partial-run paths are covered (audit 4, A4-2).
    const amounts = (V.logic as J[]).filter((v) => v.fn === "run_amount");
    expect(amounts.filter((v) => v.err === "RemainderTooSmall").length).toBeGreaterThan(20);
    expect((V.logic as J[]).filter((v) => v.fn === "record_run" && v.partial === true && v.err === null).length).toBeGreaterThan(20);
  });

  it("logic::plan_run: 2,998 complete run decisions (every error the planner can give, and every kind of plan, partial buybacks included)", () => {
    const graphs = (V.graphs as string[]).map((h) => verifyGraphBytes(fromHex(h)));
    const outcomes = new Map<string, number>();
    for (const c of V.plan_run) {
      const r = planRun({
        graph: graphs[c.g]!,
        node: c.node,
        now: b(c.now),
        states: (c.states as J[]).map(raw),
        operator: fromHex(c.operator),
        operatorSigner: c.signer === null ? null : fromHex(c.signer),
        amount: ob(c.amount),
        treasurySol: b(c.sol),
        treasuryToken: b(c.tokens),
        graduated: c.graduated,
        spot: ob(c.spot),
        reference: b(c.reference),
        seen: seenOf(c.seen),
        poolQuote: ob(c.pool_quote),
        partialSpent: b(c.partial_spent),
      });
      const where = JSON.stringify(c);
      if (c.err !== null) {
        expect(r.ok ? "ok" : r.error, where).toBe(c.err);
        outcomes.set(c.err, (outcomes.get(c.err) ?? 0) + 1);
        continue;
      }
      expect(r.ok, where).toBe(true);
      if (!r.ok) continue;
      const p = r.value;
      expect(p.kind, where).toBe(c.plan.kind);
      if (p.kind === "buyback") expect([p.amountIn, p.minOut, p.partial]).toEqual([b(c.plan.amount_in), b(c.plan.min_out), c.plan.partial]);
      if (p.kind === "burn") expect(p.amount).toBe(b(c.plan.amount));
      if (p.kind === "distribute") expect([p.shares, p.total]).toEqual([(c.plan.shares as string[]).map(b), b(c.plan.total)]);
      expect(planSpent(p)).toBe(b(c.plan.spent));
      expect(planValue(p, b(c.reference))).toBe(b(c.plan.value));
      expect(planMaxTip(p, graphs[c.g]!.nodes[c.node]!.p1)).toBe(b(c.plan.max_tip));
      const k = p.kind === "buyback" && p.partial ? "buyback-partial" : p.kind;
      outcomes.set(k, (outcomes.get(k) ?? 0) + 1);
    }
    expect(V.plan_run.length).toBe(2_998);
    for (const k of [
      "buyback",
      "buyback-partial",
      "burn",
      "distribute",
      "PremiumExceeded",
      "PriceNotObserved",
      "AmountTooSmall",
      "RemainderTooSmall",
      "WrongOperator",
      "NoOperator",
      "ConditionFalse",
      "PriceOutOfRange",
      "NotGraduated",
      "InvalidDammAccounts",
    ]) {
      expect(outcomes.get(k) ?? 0, k).toBeGreaterThan(0);
    }
  });

  it("error names and numbers are the program's (6000 + index; SwapShortfall = 6030)", () => {
    expect(AUTOPILOT_ERRORS.length).toBe(43);
    expect(autopilotErrorCode("NotALaunch")).toBe(6000);
    expect(autopilotErrorCode("SwapShortfall")).toBe(6030);
    expect(autopilotErrorCode("PoolAlreadyBound")).toBe(6039);
    // Review 4, R5: appended.
    expect(autopilotErrorCode("FreezeExpired")).toBe(6040);
    // Audit round 4: appended.
    expect(autopilotErrorCode("RemainderTooSmall")).toBe(6041);
    expect(autopilotErrorCode("NoRecipientAccount")).toBe(6042);
  });
});

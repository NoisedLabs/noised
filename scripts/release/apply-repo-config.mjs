#!/usr/bin/env node
/**
 * Writes the public repository location from scripts/release/repo-config.json
 * ({ "owner", "repo", "homepage" }) into every file that names it, so the
 * owner changes ONE value:
 *
 * - package.json (sdk, MCP server, app, LangGraph example): `repository`
 *   (with its `directory`), `homepage` and `bugs`;
 * - the root Cargo.toml `[workspace.package]`: `repository` and `homepage`
 *   (the published crates inherit both with `*.workspace = true`);
 * - the badge rows of the READMEs, between the markers
 *   `<!-- repo-config:badges:start ... -->` and `<!-- repo-config:badges:end -->`;
 * - every other link to the previous repository URL in Markdown, YAML and
 *   TOML files (for example SECURITY.md's advisory link and the
 *   solana-verify command in docs/OPERATIONS.md).
 *
 * usage: node scripts/release/apply-repo-config.mjs [--check]
 *   --check  write nothing; list what is out of date and exit 1 if anything is
 *            (the release workflow runs this before publishing).
 *
 * Plain Node 22, no dependencies. Idempotent: a second run changes nothing.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { dirname, join, relative, sep, extname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const CHECK = process.argv.includes("--check");
const posix = (p) => p.split(sep).join("/");

// ------------------------------------------------------------------ config ---
const cfg = JSON.parse(readFileSync(join(ROOT, "scripts", "release", "repo-config.json"), "utf8"));
const OWNER = String(cfg.owner ?? "");
const REPO = String(cfg.repo ?? "");
const HOMEPAGE = String(cfg.homepage ?? "");
if (!/^[A-Za-z0-9](?:[A-Za-z0-9-]{0,38})$/.test(OWNER)) throw new Error(`repo-config.json: invalid owner ${JSON.stringify(OWNER)}`);
if (!/^[A-Za-z0-9._-]{1,100}$/.test(REPO)) throw new Error(`repo-config.json: invalid repo ${JSON.stringify(REPO)}`);
if (!/^https:\/\/[^\s"'<>]+$/.test(HOMEPAGE)) throw new Error(`repo-config.json: homepage must be an https URL`);
const REPO_URL = `https://github.com/${OWNER}/${REPO}`;
if (OWNER === "TBD") console.warn(`note: owner is the placeholder "TBD"; set the real GitHub owner in scripts/release/repo-config.json before publishing`);

// ------------------------------------------------------------------ targets ---
const PACKAGES = [
  { file: "sdk/package.json", dir: "sdk" },
  { file: "packages/noised-mcp/package.json", dir: "packages/noised-mcp" },
  { file: "app/package.json", dir: "app" },
  { file: "packages/noised-mcp/examples/langgraph-operator/package.json", dir: "packages/noised-mcp/examples/langgraph-operator" },
];

const ci = `[![CI](${REPO_URL}/actions/workflows/ci.yml/badge.svg?branch=main)](${REPO_URL}/actions/workflows/ci.yml)`;
const license = `[![License: Apache-2.0](https://img.shields.io/badge/license-Apache--2.0-blue.svg)](${REPO_URL}/blob/main/LICENSE)`;
const npm = (name) => `[![npm ${name}](https://img.shields.io/npm/v/${name}.svg?label=${encodeURIComponent(name)})](https://www.npmjs.com/package/${name})`;
const crate = (name) => `[![crates.io ${name}](https://img.shields.io/crates/v/${name}.svg?label=${name})](https://crates.io/crates/${name})`;
const docsrs = (name) => `[![docs.rs](https://img.shields.io/docsrs/${name})](https://docs.rs/${name})`;
const site = `[![Website](https://img.shields.io/badge/website-${encodeURIComponent(HOMEPAGE.replace(/^https:\/\//, "").replace(/-/g, "--"))}-black.svg)](${HOMEPAGE})`;

const BADGES = [
  { file: "README.md", row: [ci, license, site, npm("@noisedlabs/sdk"), npm("@noisedlabs/mcp"), crate("noised-lmots"), crate("noised-rules")] },
  { file: "sdk/README.md", row: [npm("@noisedlabs/sdk"), ci, license] },
  { file: "packages/noised-mcp/README.md", row: [npm("@noisedlabs/mcp"), ci, license] },
  { file: "crates/noised-lmots/README.md", row: [crate("noised-lmots"), docsrs("noised-lmots"), ci, license] },
  { file: "crates/noised-rules/README.md", row: [crate("noised-rules"), docsrs("noised-rules"), ci, license] },
];
const START = "<!-- repo-config:badges:start (generated by scripts/release/apply-repo-config.mjs from scripts/release/repo-config.json; do not edit by hand) -->";
const START_RE = /<!-- repo-config:badges:start[^\n]*-->/;
const END = "<!-- repo-config:badges:end -->";

// Text files whose links to the previous repository URL are rewritten.
const TEXT_EXT = new Set([".md", ".yml", ".yaml", ".toml", ".txt"]);
const SKIP_DIRS = new Set([".git", "node_modules", "dist", ".keys", "fixtures", ".anchor", "test-ledger", "coverage"]);

// --------------------------------------------------------------- helpers ---
const changed = [];
function update(rel, before, after) {
  if (before === after) return;
  changed.push(rel);
  if (!CHECK) writeFileSync(join(ROOT, rel), after);
}
const read = (rel) => readFileSync(join(ROOT, rel), "utf8");
const eol = (text) => (text.includes("\r\n") ? "\r\n" : "\n");

/** Previous owner/repo pairs to rewrite: the one the SDK's package.json names now, plus earlier placeholders. */
function previousRepos() {
  const pairs = new Set(["TODO-OWNER/TODO-REPO", "noised-launchpad/noised"]);
  const url = JSON.parse(read("sdk/package.json"))?.repository?.url ?? "";
  const m = /github\.com\/([A-Za-z0-9-]+)\/([A-Za-z0-9._-]+?)(?:\.git)?$/.exec(url);
  if (m) pairs.add(`${m[1]}/${m[2]}`);
  pairs.delete(`${OWNER}/${REPO}`);
  return [...pairs];
}

function setKeysAfter(obj, entries, anchors) {
  // Replace values in place; insert missing keys after the first anchor key present.
  const missing = entries.filter(([k]) => !(k in obj));
  for (const [k, v] of entries) if (k in obj) obj[k] = v;
  if (missing.length === 0) return obj;
  const anchor = anchors.find((a) => a in obj);
  const out = {};
  for (const [k, v] of Object.entries(obj)) {
    out[k] = v;
    if (k === anchor) for (const [mk, mv] of missing) out[mk] = mv;
  }
  if (!anchor) for (const [mk, mv] of missing) out[mk] = mv;
  return out;
}

// Read the previous location before anything is rewritten.
const prev = previousRepos();

// -------------------------------------------------------------- package.json ---
for (const { file, dir } of PACKAGES) {
  if (!existsSync(join(ROOT, file))) continue;
  const before = read(file);
  let pkg = JSON.parse(before);
  pkg = setKeysAfter(
    pkg,
    [
      ["homepage", HOMEPAGE],
      ["bugs", { url: `${REPO_URL}/issues` }],
      ["repository", { type: "git", url: `git+${REPO_URL}.git`, directory: dir }],
    ],
    ["keywords", "description", "version"],
  );
  update(file, before, JSON.stringify(pkg, null, 2) + "\n");
}

// ---------------------------------------------------------------- Cargo.toml ---
{
  const file = "Cargo.toml";
  const before = read(file);
  const nl = eol(before);
  const lines = before.split(/\r?\n/);
  const start = lines.findIndex((l) => l.trim() === "[workspace.package]");
  if (start < 0) throw new Error("Cargo.toml: no [workspace.package] section");
  let end = lines.findIndex((l, i) => i > start && /^\s*\[/.test(l));
  if (end < 0) end = lines.length;
  for (const [key, value] of [["repository", REPO_URL], ["homepage", HOMEPAGE]]) {
    const line = `${key} = "${value}"`;
    const at = lines.findIndex((l, i) => i > start && i < end && new RegExp(`^\\s*${key}\\s*=`).test(l));
    if (at >= 0) lines[at] = line;
    else {
      let last = end - 1;
      while (last > start && lines[last].trim() === "") last--;
      lines.splice(last + 1, 0, line);
      end++;
    }
  }
  update(file, before, lines.join(nl));
}

// --------------------------------------------------------------- README badges ---
for (const { file, row } of BADGES) {
  if (!existsSync(join(ROOT, file))) continue;
  const before = read(file);
  const nl = eol(before);
  const block = [START, row.join(" "), END].join(nl);
  let after;
  const s = before.search(START_RE);
  if (s >= 0) {
    const e = before.indexOf(END, s);
    if (e < 0) throw new Error(`${file}: badge start marker without end marker`);
    after = before.slice(0, s) + block + before.slice(e + END.length);
  } else {
    const h1 = /^# .*$/m.exec(before);
    if (!h1) throw new Error(`${file}: no "# " title to put the badges under`);
    const at = h1.index + h1[0].length;
    after = before.slice(0, at) + nl + nl + block + before.slice(at);
  }
  update(file, before, after);
}

// ------------------------------------------------- links to the previous URL ---
if (prev.length > 0) {
  const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const re = new RegExp(`https://github\\.com/(?:${prev.map(esc).join("|")})(?![A-Za-z0-9_-])`, "g");
  const walk = (dir) => {
    for (const entry of readdirSync(join(ROOT, dir), { withFileTypes: true })) {
      const rel = dir ? `${dir}/${entry.name}` : entry.name;
      if (entry.isDirectory()) {
        if (SKIP_DIRS.has(entry.name) || /^target/.test(entry.name)) continue;
        walk(rel);
      } else if (entry.isFile() && TEXT_EXT.has(extname(entry.name).toLowerCase())) {
        const before = read(rel);
        const after = before.replace(re, REPO_URL);
        update(posix(relative(ROOT, join(ROOT, rel))), before, after);
      }
    }
  };
  walk("");
}

// ------------------------------------------------------------------- report ---
const unique = [...new Set(changed)];
if (unique.length === 0) {
  console.log(`up to date: ${REPO_URL} (homepage ${HOMEPAGE})`);
} else if (CHECK) {
  console.error(`out of date (run node scripts/release/apply-repo-config.mjs):\n  ${unique.join("\n  ")}`);
  process.exit(1);
} else {
  console.log(`wrote ${REPO_URL} (homepage ${HOMEPAGE}) into:\n  ${unique.join("\n  ")}`);
}
